@app.post("/api/run", response_model=RunResponse)
def run_code(request: RunRequest):
    """Run a Python snippet for local development with a short time limit."""
    if not ENABLE_CODE_EXECUTION:
        raise HTTPException(status_code=503, detail="Code execution is disabled on this server.")

    started_at = time.perf_counter()

    try:
        with tempfile.TemporaryDirectory() as temporary_directory:
            file_path = Path(temporary_directory) / "user_code.py"
            file_path.write_text(request.code, encoding="utf-8")
            with tempfile.TemporaryFile(mode="w+b") as stdout_file, tempfile.TemporaryFile(mode="w+b") as stderr_file:
                process = subprocess.Popen(
                    [sys.executable, "-I", str(file_path)],
                    stdout=stdout_file,
                    stderr=stderr_file,
                    cwd=temporary_directory,
                )
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()
                    return RunResponse(
                        output="",
                        error="Execution stopped after 5 seconds.",
                        execution_time=round(time.perf_counter() - started_at, 3),
                        timed_out=True,
                    )

                stdout_file.seek(max(0, stdout_file.tell() - 10000))
                stderr_file.seek(max(0, stderr_file.tell() - 10000))
                output = stdout_file.read().decode("utf-8", errors="replace").replace("\r\n", "\n")
                error = stderr_file.read().decode("utf-8", errors="replace").replace("\r\n", "\n")
    except subprocess.TimeoutExpired as error:
        return RunResponse(
            output=error.stdout or "",
            error="Execution stopped after 5 seconds.",
            execution_time=round(time.perf_counter() - started_at, 3),
            timed_out=True,
        )

    return RunResponse(
        output=output,
        error=error,
        execution_time=round(time.perf_counter() - started_at, 3),
        timed_out=False,
    )


@app.post("/api/review", response_model=ReviewResponse)
async def review_code(request: ReviewRequest):
    api_key = os.getenv("GEMINI_API_KEY")
    model = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")

    if not api_key:
        return ReviewResponse(
            review=build_local_review(request.code, request.language, request.instructions),
            model="local-review-fallback",
        )

    prompt = f"""You are a patient code reviewer for beginners.

Review this {request.language} code.

{request.code}

Instructions: {request.instructions}

Return a clear review with these headings:
1. Summary
2. Bugs and risks
3. Code quality
4. Time and space complexity
5. Simple improvements

If there are no problems in a section, say so. Use plain text and do not use markdown tables."""

    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
    payload = {"contents": [{"parts": [{"text": prompt}]}]}

    try:
        async with httpx.AsyncClient(timeout=45) as client:
            response = await client.post(url, params={"key": api_key}, json=payload)
            response.raise_for_status()
    except (httpx.HTTPStatusError, httpx.RequestError):
        fallback_review = build_local_review(request.code, request.language, request.instructions)
        return ReviewResponse(review=fallback_review, model="local-review-fallback")

    data = response.json()
    candidates = data.get("candidates", [])
    if not candidates:
        return ReviewResponse(
            review=build_local_review(request.code, request.language, request.instructions),
            model="local-review-fallback",
        )

    review_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
    if not review_text:
        return ReviewResponse(
            review=build_local_review(request.code, request.language, request.instructions),
            model="local-review-fallback",
        )

    return ReviewResponse(review=review_text, model=model)
