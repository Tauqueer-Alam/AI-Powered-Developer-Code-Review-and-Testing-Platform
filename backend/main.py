def init_db():
    if not DATABASE_URL:
        DB_PATH.parent.mkdir(parents=True, exist_ok=True)

    id_definition = (
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if database_engine.dialect.name == "postgresql"
        else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    with database_engine.begin() as connection:
        connection.execute(text(f"""
            CREATE TABLE IF NOT EXISTS users (
                id {id_definition},
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                password_salt TEXT NOT NULL,
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """))

    user_columns = {column["name"] for column in inspect(database_engine).get_columns("users")}
    missing_columns = []
    if "password_salt" not in user_columns:
        missing_columns.append("password_salt TEXT")
    if "created_at" not in user_columns:
        missing_columns.append("created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP")

    for column_definition in missing_columns:
        with database_engine.begin() as connection:
            connection.execute(text(f"ALTER TABLE users ADD COLUMN {column_definition}"))


def hash_password(password: str, salt: str | None = None):
    if salt is None:
        salt = secrets.token_hex(16)
    derived = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt.encode("utf-8"), 100_000)
    return salt, base64.b64encode(derived).decode("utf-8")


def verify_password(password: str, salt: str, hashed_password: str) -> bool:
    _, derived = hash_password(password, salt)
    return hmac.compare_digest(derived, hashed_password)


def create_token(user_id: int) -> str:
    issued_at = int(time.time())
    payload = f"{user_id}:{issued_at}:{secrets.token_urlsafe(16)}"
    encoded_payload = base64.urlsafe_b64encode(payload.encode("utf-8")).decode("utf-8").rstrip("=")
    signature = hmac.new(AUTH_SECRET.encode("utf-8"), encoded_payload.encode("ascii"), hashlib.sha256).digest()
    encoded_signature = base64.urlsafe_b64encode(signature).decode("ascii").rstrip("=")
    return f"{encoded_payload}.{encoded_signature}"


def decode_token(token: str) -> int | None:
    try:
        encoded_payload, encoded_signature = token.split(".", 1)
        expected_signature = hmac.new(AUTH_SECRET.encode("utf-8"), encoded_payload.encode("ascii"), hashlib.sha256).digest()
        supplied_signature = base64.urlsafe_b64decode(encoded_signature + "=" * (-len(encoded_signature) % 4))
        if not hmac.compare_digest(supplied_signature, expected_signature):
            return None

        decoded = base64.urlsafe_b64decode(encoded_payload + "=" * (-len(encoded_payload) % 4)).decode("utf-8")
        user_id_text, issued_at_text, _ = decoded.split(":", 2)
        if int(time.time()) - int(issued_at_text) > TOKEN_TTL_SECONDS:
            return None
        user_id = int(user_id_text)
        return user_id
    except (ValueError, TypeError, UnicodeDecodeError, binascii.Error):
        return None


