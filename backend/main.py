@app.post("/api/auth/register", response_model=AuthResponse)
def register_user(request: RegisterRequest):
    email = request.email.strip().lower()
    name = request.name.strip()
    if len(name) < 2:
        raise HTTPException(status_code=400, detail="Name must contain at least two non-space characters.")
    if "@" not in email or email.startswith("@") or email.endswith("@"):
        raise HTTPException(status_code=400, detail="Invalid email address.")

    with database_engine.begin() as conn:
        existing = conn.execute(text("SELECT id FROM users WHERE email = :email"), {"email": email}).mappings().first()
        if existing:
            raise HTTPException(status_code=409, detail="An account with this email already exists.")

        salt, password_hash = hash_password(request.password)
        cursor = conn.execute(
            text("INSERT INTO users (name, email, password_hash, password_salt) VALUES (:name, :email, :password_hash, :password_salt) RETURNING id"),
            {"name": name, "email": email, "password_hash": password_hash, "password_salt": salt},
        )
        user_id = cursor.scalar_one()
        user_row = conn.execute(
            text("SELECT id, name, email, created_at FROM users WHERE id = :id"),
            {"id": user_id},
        ).mappings().first()

    token = create_token(user_id)
    return AuthResponse(
        token=token,
        user=public_user(user_row),
    )


@app.post("/api/auth/login", response_model=AuthResponse)
def login_user(request: LoginRequest):
    email = request.email.strip().lower()

    with database_engine.begin() as conn:
        user_row = conn.execute(
            text("SELECT id, name, email, password_hash, password_salt, created_at FROM users WHERE email = :email"),
            {"email": email},
        ).mappings().first()

    if not user_row:
        raise HTTPException(status_code=401, detail="Invalid email or password.")

    if not user_row["password_salt"] or not verify_password(request.password, user_row["password_salt"], user_row["password_hash"]):
        raise HTTPException(status_code=401, detail="Invalid email or password.")

    token = create_token(user_row["id"])
    return AuthResponse(
        token=token,
        user=UserPublic(
            id=user_row["id"],
            name=user_row["name"],
            email=user_row["email"],
            created_at=str(user_row["created_at"]),
        ),
    )


@app.get("/api/auth/me", response_model=UserPublic)
def get_current_user(authorization: str | None = Header(default=None, alias="Authorization")):
    if not authorization or not authorization.startswith("Bearer "):
        raise HTTPException(status_code=401, detail="Missing or invalid auth token.")

    token = authorization.split(" ", 1)[1]
    user_id = decode_token(token)
    if user_id is None:
        raise HTTPException(status_code=401, detail="Invalid auth token.")

    with database_engine.begin() as conn:
        row = conn.execute(
            text("SELECT id, name, email, created_at FROM users WHERE id = :id"),
            {"id": user_id},
        ).mappings().first()

    if row is None:
        raise HTTPException(status_code=401, detail="User not found.")

    return public_user(row)


def build_local_test_cases(code: str, language: str) -> str:
    """Generate simple, beginner-friendly unit tests based on a function snippet."""
    stripped = code.strip()
    function_name = "sample_function"
    if "def " in stripped:
        match = re.search(r"def\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(", stripped)
        if match:
            function_name = match.group(1)

    if "factorial" in function_name.lower() or "factorial" in code.lower():
        tests = [
            f"def test_{function_name}_zero_case():",
            "    result = " + function_name + "(0)",
            "    assert result == 1",
            "",
            f"def test_{function_name}_small_number():",
            "    result = " + function_name + "(5)",
            "    assert result == 120",
            "",
            f"def test_{function_name}_one_case():",
            "    result = " + function_name + "(1)",
            "    assert result == 1",
        ]
        return "\n".join(tests)

    tests = [
        f"def test_{function_name}_basic_case():",
        "    result = " + function_name + "([3, 8, 1, 6])",
        "    assert result == 8",
        "",
        f"def test_{function_name}_single_value():",
        "    result = " + function_name + "([42])",
        "    assert result == 42",
        "",
        f"def test_{function_name}_negative_numbers():",
        "    result = " + function_name + "([-5, -2, -9, -1])",
        "    assert result == -1",
    ]

    if "raise ValueError" in code or "ValueError" in code:
        tests.extend([
            "",
            f"def test_{function_name}_empty_list_raises_error():",
            "    try:",
            "        " + function_name + "([])",
            "    except ValueError:",
            "        pass",
            "    else:",
            "        raise AssertionError('Expected ValueError for an empty list')",
        ])

    return "\n".join(tests)


