def build_quality_score(code: str, language: str) -> tuple[int, str]:
    score = 82
    lowered = code.lower()
    if "def " not in code:
        score -= 20
    if "return " not in code:
        score -= 10
    if "if " in code:
        score += 6
    if "for " in code:
        score += 4
    if "pass" in lowered or "todo" in lowered:
        score -= 18
    if "raise valueerror" in lowered or "assert" in lowered:
        score += 8
    if "print(" in lowered:
        score -= 5
    if "try:" in code or "except" in code:
        score += 8
    score = max(0, min(100, score))
    summary = f"Quality score: {score}/100 for this {language} snippet. The code is readable and structured, but edge-case handling and validation can still improve its reliability."
    return score, summary


